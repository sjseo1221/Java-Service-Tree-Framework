-- nested-set 정합성 검사 (읽기 전용). T_TREE 를 실제 테이블명으로 바꿔서 실행한다.
-- bad > 0 인 행이 문제다. 전부 0 이면 정상. 검증: H2 2.2 MODE=MySQL (MySQL 8 실DB 미검증)
SELECT 'ROOT_COUNT' AS chk, CASE WHEN COUNT(*) = 1 THEN 0 ELSE 1 END AS bad FROM T_TREE WHERE C_PARENTID = 0
UNION ALL
SELECT 'ROOT_LEFT_NOT_1', COUNT(*) FROM T_TREE WHERE C_PARENTID = 0 AND C_LEFT <> 1
UNION ALL
SELECT 'MAX_RIGHT_NE_2N', CASE WHEN MAX(C_RIGHT) = 2 * COUNT(*) THEN 0 ELSE 1 END FROM T_TREE
UNION ALL
SELECT 'LEFT_GE_RIGHT', COUNT(*) FROM T_TREE WHERE C_LEFT >= C_RIGHT
UNION ALL
SELECT 'DUP_LEFT_RIGHT', COUNT(*) FROM (
  SELECT v FROM (SELECT C_LEFT AS v FROM T_TREE UNION ALL SELECT C_RIGHT FROM T_TREE) a
  GROUP BY v HAVING COUNT(*) > 1) d
UNION ALL
SELECT 'MISSING_PARENT', COUNT(*) FROM T_TREE c
  WHERE c.C_PARENTID <> 0 AND NOT EXISTS (SELECT 1 FROM T_TREE p WHERE p.C_ID = c.C_PARENTID)
UNION ALL
SELECT 'NOT_INSIDE_PARENT', COUNT(*) FROM T_TREE c JOIN T_TREE p ON p.C_ID = c.C_PARENTID
  WHERE NOT (p.C_LEFT < c.C_LEFT AND c.C_RIGHT < p.C_RIGHT AND c.C_LEVEL = p.C_LEVEL + 1)
UNION ALL
SELECT 'BAD_POSITION_SET', COUNT(*) FROM (
  SELECT C_PARENTID FROM T_TREE GROUP BY C_PARENTID
  HAVING MIN(C_POSITION) <> 0 OR MAX(C_POSITION) <> COUNT(*) - 1 OR COUNT(DISTINCT C_POSITION) <> COUNT(*)) g
UNION ALL
SELECT 'POS_ORDER_NE_LEFT_ORDER', COUNT(*) FROM T_TREE a JOIN T_TREE b
  ON a.C_PARENTID = b.C_PARENTID AND a.C_POSITION < b.C_POSITION AND a.C_LEFT > b.C_LEFT
UNION ALL
SELECT 'EMPTY_TITLE', COUNT(*) FROM T_TREE WHERE C_TITLE IS NULL OR C_TITLE = ''
;
